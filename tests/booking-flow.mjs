import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import path from 'node:path';

const browser = await chromium.launch({ headless: true });
const base = process.env.TEST_URL || 'http://127.0.0.1:5175';
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', (error) => errors.push(error.message));
page.on('dialog', (dialog) => dialog.accept());
try {
  await page.goto(base);
  await page.getByText('Catálogo de demostración', { exact: false }).waitFor();
  await page.screenshot({ path: path.join(process.env.TEMP || '.', 'gringacho-catalog-desktop.png'), fullPage: true });
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Gruta de Benagil en barco', exact: true }) });
  await card.getByRole('button', { name: 'Solicitar reserva' }).click();
  await page.getByLabel('Tu nombre', { exact: true }).fill('Ana Prueba');
  await page.getByLabel('Habitación', { exact: true }).fill('204');
  await page.getByLabel('Teléfono o email').fill('ana@example.com');
  await page.getByLabel('Personas', { exact: true }).fill('2');
  await page.getByLabel('Fecha solicitada', { exact: true }).fill('2030-03-01');
  await page.getByLabel('Hora solicitada', { exact: true }).fill('10:00');
  await page.getByRole('button', { name: 'Solicitar reserva y generar cupón' }).click();
  await page.getByRole('heading', { name: 'Tu cupón para recepción' }).waitFor();
  let sale = await page.evaluate(() => JSON.parse(localStorage.getItem('gringacho_sales')).find((s) => s.guestName === 'Ana Prueba'));
  assert.equal(sale.status, 'Reservado'); assert.equal(sale.bookingStatus, 'Solicitada');
  assert.equal(sale.amount, 120); assert.equal(sale.providerAmount, 80);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Descargar cupón' }).click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(), `${sale.bookingCode}.txt`);
  await page.screenshot({ path: path.join(process.env.TEMP || '.', 'gringacho-coupon-desktop.png'), fullPage: true });
  await page.evaluate(() => {
    localStorage.setItem('gringacho_admin_session', JSON.stringify({ id: 2, name: 'Recepción Demo', role: 'hotel_admin', hotelId: 101 }));
    const recs = JSON.parse(localStorage.getItem('gringacho_recommendations'));
    recs.find((r) => r.id === 6).price = 100;
    localStorage.setItem('gringacho_recommendations', JSON.stringify(recs));
  });
  await page.goto(`${base}/admin`);
  const inbox = page.locator('.reception-panel');
  await page.getByLabel('Buscar reserva', { exact: true }).fill(sale.bookingCode);
  await inbox.getByRole('button', { name: 'Confirmar disponibilidad' }).click();
  await page.getByRole('button', { name: 'Sí, la empresa confirmó', exact: true }).click();
  await page.getByLabel('Estado', { exact: true }).selectOption('ready');
  await inbox.getByRole('button', { name: 'Cobrar', exact: true }).click();
  await inbox.getByRole('button', { name: 'Registrar efectivo recibido', exact: true }).click();
  await page.getByRole('button', { name: 'Sí, recibí el efectivo', exact: true }).click();
  await page.getByText('Este cupón ya está cobrado.', { exact: true }).waitFor();
  sale = await page.evaluate(() => JSON.parse(localStorage.getItem('gringacho_sales')).find((s) => s.guestName === 'Ana Prueba'));
  assert.equal(sale.status, 'Cobrado'); assert.equal(sale.amount, 120);
  assert.equal(sale.providerAmount, 80); assert.equal(sale.collectedBy, 'Recepción Demo');
  assert.equal(await inbox.getByRole('button', { name: 'Registrar efectivo recibido', exact: true }).count(), 0);
  const concurrency = await page.evaluate(async () => {
    const { processBooking } = await import('/src/services/adminDataService.js');
    const sales = JSON.parse(localStorage.getItem('gringacho_sales'));
    const source = sales.find((s) => s.guestName === 'Ana Prueba');
    const fresh = { ...source, id: crypto.randomUUID(), bookingCode: 'LL-CONCURRENCY', status: 'Reservado', paidAt: null };
    localStorage.setItem('gringacho_sales', JSON.stringify([fresh, ...sales]));
    const user = { role: 'hotel_admin', hotelId: 101, name: 'Concurrent Test' };
    const results = await Promise.allSettled([processBooking(fresh, 'collect', user), processBooking(fresh, 'collect', user)]);
    localStorage.setItem('gringacho_sales', JSON.stringify(sales));
    return results.map((r) => r.status);
  });
  assert.deepEqual(concurrency.sort(), ['fulfilled', 'rejected']);
  await page.screenshot({ path: path.join(process.env.TEMP || '.', 'gringacho-inbox-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(process.env.TEMP || '.', 'gringacho-inbox-mobile.png'), fullPage: true });
  await page.goto(base);
  await page.getByRole('button', { name: 'Alquiler de motos', exact: true }).click();
  await page.getByRole('button', { name: 'Solicitar reserva', exact: true }).click();
  await page.getByLabel('Tu nombre', { exact: true }).fill('Alquiler Prueba');
  await page.getByLabel('Teléfono o email').fill('test@example.com');
  await page.getByLabel('Fecha de entrega', { exact: true }).fill('2030-03-01');
  await page.getByLabel('Hora de entrega', { exact: true }).fill('10:00');
  await page.getByLabel('Fecha de devolución', { exact: true }).fill('2030-03-03');
  await page.getByLabel('Hora de devolución', { exact: true }).fill('10:00');
  await page.screenshot({ path: path.join(process.env.TEMP || '.', 'gringacho-form-mobile.png') });
  await page.getByRole('button', { name: 'Solicitar reserva y generar cupón' }).click();
  await page.getByRole('heading', { name: 'Tu cupón para recepción' }).waitFor();
  const rental = await page.evaluate(() => JSON.parse(localStorage.getItem('gringacho_sales')).find((s) => s.guestName === 'Alquiler Prueba'));
  assert.equal(rental.amount, 80); assert.equal(rental.endDate, '2030-03-03');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(process.env.TEMP || '.', 'gringacho-coupon-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.getByRole('button', { name: 'Excursiones', exact: true }).click();
  const dolphin = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Avistaje de delfines', exact: true }) });
  await dolphin.getByRole('button', { name: 'Solicitar reserva' }).click();
  await page.getByLabel('Tu nombre', { exact: true }).fill('Error de guardado');
  await page.getByLabel('Teléfono o email').fill('test@example.com');
  await page.getByLabel('Fecha solicitada', { exact: true }).fill('2030-03-01');
  await page.getByLabel('Hora solicitada', { exact: true }).fill('10:00');
  await page.evaluate(() => {
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function (key, value) {
      if (key === 'gringacho_sales') throw new Error('No se pudo guardar la solicitud de prueba.');
      return original.call(this, key, value);
    };
  });
  await page.getByRole('button', { name: 'Solicitar reserva y generar cupón' }).click();
  await page.getByRole('alert').filter({ hasText: 'No se pudo guardar' }).waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Tu cupón para recepción' }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: guest coupon, download, availability confirmation, cash, historical prices, no second charge, rental and mobile layout.');
} catch (error) {
  console.log((await page.locator('body').innerText()).slice(0, 5000));
  await page.screenshot({ path: path.join(process.env.TEMP || '.', 'gringacho-test-failure.png'), fullPage: true });
  throw error;
} finally { await browser.close(); }
